# name: common_digit_multi_example_contrast
# description: For sets of >=2 examples that all contain a common digit, yes rate for non-example targets containing a common digit minus yes rate for non-example targets containing none of the examples' digits; observed above null means the model under-produces contains-digit generalization from multiple examples (rule posterior too diffuse), below means it over-produces it.
def test_statistic(df):
    E = df["number_set"].astype(str).str.split(",", expand=True).apply(pd.to_numeric, errors="coerce").to_numpy(dtype=float)
    present = ~np.isnan(E)
    Ei = np.where(present, E, 0).astype(int)
    def dmask(a):
        m = (1 << (a % 10)) | np.where(a >= 10, 1 << ((a // 10) % 10), 0) | np.where(a >= 100, 2, 0)
        return np.where(a > 0, m, 0)
    EM = dmask(Ei)
    union = np.bitwise_or.reduce(EM, axis=1)
    inter = np.bitwise_and.reduce(np.where(present, EM, 1023), axis=1)
    t = df["target"].astype(int).to_numpy()
    TM = dmask(t)
    r = df["rating"].astype(float).to_numpy()
    n_ex = present.sum(axis=1)
    is_ex = (Ei == t[:, None]).any(axis=1)
    def rate(m):
        return float(r[m].mean()) if m.sum() > 0 else 0.0
    base = (n_ex >= 2) & (inter > 0) & ~is_ex
    return rate(base & ((TM & inter) > 0)) - rate(base & ((TM & union) == 0))
