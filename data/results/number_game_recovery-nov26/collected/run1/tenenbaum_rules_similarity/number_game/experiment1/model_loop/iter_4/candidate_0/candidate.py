"""Bayesian concept learning under mixed weak/strong sampling.

People do Bayesian concept learning over 45 rules and all intervals of 1..100,
with a prior mass per concept family (the two exception rules in their own
family), but each example is believed to have been generated by the program
from its concept (strong sampling, the size principle) only with a learned
probability theta; otherwise it is a random number from 1..100 that merely
passed the program's test (weak sampling). 10% of examples are still treated as
noise. "Yes" is the posterior probability that the concept contains the target.
The one change from the family-prior model is this learned weak/strong mix,
which blunts the size principle, most strongly for large concepts.
"""

import numpy as np
import pymc as pm
import pytensor.tensor as pt

ALPHA = 0.9
NUMBERS = np.arange(1, 101)


def rule_concepts():
    rules = {
        "odd": [n for n in NUMBERS if n % 2 == 1],
        "primes": [n for n in NUMBERS if n > 1 and all(n % a for a in range(2, int(n**0.5) + 1))],
        "squares": [n * n for n in range(1, 11)],
        "cubes": [n**3 for n in range(1, 5)],
        "powers of 2, not 32": [2, 4, 8, 16, 64],
        "powers of 2, or 37": [2, 4, 8, 16, 32, 37, 64],
        "even": list(range(2, 101, 2)),
    }
    rules.update({f"multiples of {m}": list(range(m, 101, m)) for m in [3, 4, 5, 6, 7, 8, 9, 11, 12]})
    rules.update({f"powers of {m}": [m**k for k in range(1, 8) if m**k <= 100] for m in range(2, 11)})
    rules.update({f"ends in {d}": [n for n in NUMBERS if n % 10 == d] for d in range(10)})
    rules.update({f"contains digit {d}": [n for n in NUMBERS if str(d) in str(n)] for d in range(10)})
    return rules


def family(name):
    if name in ("odd", "even"):
        return 0
    if name.startswith("multiples"):
        return 2
    if name.startswith("ends"):
        return 3
    if name.startswith("contains"):
        return 4
    if name.startswith("powers of 2,"):
        return 5
    return 1


_RULES = rule_concepts()
RULE_NAMES, RULES = list(_RULES), list(_RULES.values())
N_RULES = len(RULES)
RULE_FAMILY = np.array([family(n) for n in RULE_NAMES])
FAMILY_SIZE = np.bincount(RULE_FAMILY).astype("float64")
INTERVALS = [list(range(m, n + 1)) for m in NUMBERS for n in range(m, 101)]
N_INTERVALS = len(INTERVALS)
MEMBERSHIP = np.array([np.isin(NUMBERS, c) for c in RULES + INTERVALS], dtype="float64")
CONCEPT_SIZE = MEMBERSHIP.sum(axis=1)
CONCEPT_FAMILY = np.concatenate([RULE_FAMILY, np.full(N_INTERVALS, 6)])
LOG_PRIOR_SHARE = -np.log(np.concatenate([FAMILY_SIZE, [N_INTERVALS]]))[CONCEPT_FAMILY]
LOG_NOISE = np.log((1 - ALPHA) / 100)

with pm.Model() as model:
    n_in = pm.Data("n_in", np.zeros((1, len(CONCEPT_SIZE))))  # examples inside each concept
    n_out = pm.Data("n_out", np.zeros((1, len(CONCEPT_SIZE))))  # examples outside it
    row_cell = pm.Data("row_cell", np.zeros(1, dtype="int64"))
    rating = pm.Data("rating", np.zeros(1, dtype="int64"))

    family_weight = pm.Dirichlet("family_weight", a=np.ones(7))
    theta = pm.Beta("theta", alpha=2.0, beta=2.0)  # probability an example is strongly sampled

    log_prior = pt.log(family_weight)[CONCEPT_FAMILY] + LOG_PRIOR_SHARE
    p_member = ALPHA * (theta / CONCEPT_SIZE + (1 - theta) / 100.0) + (1 - ALPHA) / 100.0
    log_joint = log_prior[None, :] + n_in * pt.log(p_member)[None, :] + n_out * LOG_NOISE
    posterior = pt.exp(log_joint - pt.logsumexp(log_joint, axis=1, keepdims=True))
    in_concept = posterior @ pt.as_tensor(MEMBERSHIP)

    p_yes = pm.Deterministic("p_yes", pt.clip(in_concept.reshape((-1,))[row_cell], 1e-6, 1 - 1e-6))
    pm.Bernoulli("response", p=p_yes, observed=rating)


def prepare_observed(rows):
    sets = [tuple(int(x) for x in str(r["number_set"]).split(",")) for r in rows]
    unique = list(dict.fromkeys(sets))
    index = {s: i for i, s in enumerate(unique)}
    n_in = np.stack([MEMBERSHIP[:, np.array(s) - 1].sum(axis=1) for s in unique])
    n_out = np.array([len(s) for s in unique], dtype="float64")[:, None] - n_in
    return {
        "n_in": n_in,
        "n_out": n_out,
        "row_cell": np.array([index[s] * 100 + int(r["target"]) - 1 for s, r in zip(sets, rows)], dtype="int64"),
        "rating": np.array([int(r["rating"]) for r in rows], dtype="int64"),
    }
