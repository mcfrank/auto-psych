"""Rule-only Bayesian concept learning (no magnitude/interval hypotheses).

People generalize only through arithmetic and digit rules, never through
numerical magnitude: they weigh 45 candidate rules (parity, primes, squares,
cubes, powers, multiples of k, ends in d, contains d) by how well each explains
the examples under the size principle, and say "yes" with the posterior
probability that the target obeys the rule. There are no interval hypotheses,
so a target between the examples that breaks their shared rules is rejected.
Free parameters: how reliably examples come from the rule (the rest are
uniform 1..100 noise), and a small response lapse.
"""

import numpy as np
import pymc as pm
import pytensor.tensor as pt

NUMBERS = np.arange(1, 101)


def rule_concepts():
    rules = {
        "odd": [n for n in NUMBERS if n % 2 == 1],
        "even": list(range(2, 101, 2)),
        "primes": [n for n in NUMBERS if n > 1 and all(n % a for a in range(2, int(n**0.5) + 1))],
        "squares": [n * n for n in range(1, 11)],
        "cubes": [n**3 for n in range(1, 5)],
        "powers of 2, not 32": [2, 4, 8, 16, 64],
        "powers of 2, or 37": [2, 4, 8, 16, 32, 37, 64],
    }
    rules.update({f"multiples of {m}": list(range(m, 101, m)) for m in [3, 4, 5, 6, 7, 8, 9, 11, 12]})
    rules.update({f"powers of {m}": [m**k for k in range(1, 8) if m**k <= 100] for m in range(2, 11)})
    rules.update({f"ends in {d}": [n for n in NUMBERS if n % 10 == d] for d in range(10)})
    rules.update({f"contains digit {d}": [n for n in NUMBERS if str(d) in str(n)] for d in range(10)})
    return list(rules.values())


RULES = rule_concepts()
N_RULES = len(RULES)
MEMBERSHIP = np.array([np.isin(NUMBERS, c) for c in RULES], dtype="float64")  # (rules, 100)
SIZE = MEMBERSHIP.sum(axis=1)


def prepare_observed(rows):
    sets = [tuple(int(x) for x in str(r["number_set"]).split(",")) for r in rows]
    unique = list(dict.fromkeys(sets))
    index = {s: i for i, s in enumerate(unique)}
    # Per distinct set and rule: how many examples the rule contains (each has
    # probability 1/|rule|) and how many it misses (noise only).
    counts = np.zeros((len(unique), N_RULES))
    misses = np.zeros((len(unique), N_RULES))
    for i, s in enumerate(unique):
        m = MEMBERSHIP[:, np.array(s) - 1]
        counts[i] = m.sum(axis=1)
        misses[i] = len(s) - counts[i]
    return {
        "hit_count": counts,
        "miss_count": misses,
        "row_cell": np.array([index[s] * 100 + int(r["target"]) - 1 for s, r in zip(sets, rows)], dtype="int64"),
        "rating": np.array([int(r["rating"]) for r in rows], dtype="int64"),
    }


with pm.Model() as model:
    hit_count = pm.Data("hit_count", np.zeros((1, N_RULES)))
    miss_count = pm.Data("miss_count", np.zeros((1, N_RULES)))
    row_cell = pm.Data("row_cell", np.zeros(1, dtype="int64"))
    rating = pm.Data("rating", np.zeros(1, dtype="int64"))

    # Probability an example is generated by the hidden rule (vs uniform noise).
    reliability = pm.Beta("reliability", alpha=9.0, beta=1.0)
    lapse = pm.Beta("lapse", alpha=1.0, beta=9.0)

    log_member = pt.log(reliability / SIZE + (1 - reliability) / 100.0)[None, :]
    log_nonmember = pt.log((1 - reliability) / 100.0)
    log_lik = hit_count * log_member + miss_count * log_nonmember  # equal rule priors
    posterior = pt.exp(log_lik - pt.logsumexp(log_lik, axis=1, keepdims=True))
    in_rule = posterior @ pt.as_tensor(MEMBERSHIP)  # (sets, 100)

    p_member = in_rule.reshape((-1,))[row_cell]
    p_yes = pm.Deterministic("p_yes", pt.clip((1 - lapse) * p_member + lapse * 0.5, 1e-6, 1 - 1e-6))
    pm.Bernoulli("response", p=p_yes, observed=rating)
