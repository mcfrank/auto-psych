"""Residue-class (arithmetic progression) concept learning.

People are Bayesian concept learners (tempered size principle, lapses to
guessing), but their rule space is generated by one grammar: every arithmetic
progression {x : x mod g == r} (steps g = 2..20 with any remainder, and pure
multiples of g up to 50), which subsumes even/odd, multiples of g and "ends in
d" (g = 10), alongside powers, squares/cubes/primes, contained digits and all
intervals of 1..100. A progression's prior weight falls as g^-alpha, with extra
weight for remainder 0 (pure multiples) and for step 10 (decimal final digit).
"""

import numpy as np
import pymc as pm
import pytensor.tensor as pt

EPSILON = 0.1
NUMBERS = np.arange(1, 101)
MAX_EX = 4
N_GROUPS = MAX_EX * (MAX_EX + 1) // 2 + 1


def _rules():
    res, res_g, res_r0, res_g10 = [], [], [], []
    for g in range(2, 51):
        for r in (range(g) if g <= 20 else [0]):
            res.append([i for i in NUMBERS if i % g == r])
            res_g.append(g)
            res_r0.append(1.0 if r == 0 else 0.0)
            res_g10.append(1.0 if g == 10 else 0.0)
    other, fam = [], []
    for b in range(2, 11):
        other.append([b ** k for k in range(1, 8) if b ** k <= 100]); fam.append(1)
    other.append([i * i for i in range(1, 11)]); fam.append(2)
    other.append([1, 8, 27, 64]); fam.append(2)
    other.append([p for p in range(2, 101) if all(p % q for q in range(2, p))]); fam.append(2)
    for d in range(1, 10):
        other.append([i for i in NUMBERS if str(d) in str(i)]); fam.append(3)
    return res, np.array(res_g, float), np.array(res_r0), np.array(res_g10), other, np.array(fam)


RES, RES_G, RES_R0, RES_G10, OTHER, OTHER_FAM = _rules()
RULES = RES + OTHER
N_RES = len(RES)
N_RULES = len(RULES)
FAM_COUNT = np.array([N_RES] + [np.sum(OTHER_FAM == f) for f in (1, 2, 3)], float)
OTHER_LOGU = -np.log(FAM_COUNT[OTHER_FAM])  # uniform within non-progression families
N_INTERVALS = 5050
RULE_MEMBERSHIP = np.array([np.isin(NUMBERS, c) for c in RULES], dtype="float64")
RULE_LOG_LIK = np.log(RULE_MEMBERSHIP * (1 - EPSILON) / RULE_MEMBERSHIP.sum(axis=1, keepdims=True) + EPSILON / 100)
SIZES = np.arange(1, 101)
LOG_IN = np.log((1 - EPSILON) / SIZES + EPSILON / 100)
LOG_OUT = np.log(EPSILON / 100)


def _set_cells(s):
    order = sorted(range(len(s)), key=lambda k: s[k])
    vals = [s[k] for k in order]
    runs = [(i, j) for i in range(len(vals)) for j in range(i, len(vals))]
    run_id = {r: g + 1 for g, r in enumerate(runs)}
    counts = np.zeros((N_GROUPS, 100))
    in_counts = np.zeros((N_GROUPS, 100, 100))
    for m in range(1, 101):
        for n in range(m, 101):
            inside = [i for i, v in enumerate(vals) if m <= v <= n]
            g = run_id[(inside[0], inside[-1])] if inside else 0
            counts[g, n - m] += 1
            in_counts[g, n - m, m - 1:n] += 1
    member = np.zeros((N_GROUPS, MAX_EX))
    for (i, j), g in run_id.items():
        for k in order[i:j + 1]:
            member[g, k] = 1.0
    g_idx, size_idx = np.nonzero(counts)
    c = counts[g_idx, size_idx]
    return c, size_idx, member[g_idx], in_counts[g_idx, size_idx] / c[:, None]


def prepare_observed(rows):
    sets = [tuple(int(x) for x in str(r["number_set"]).split(",")) for r in rows]
    unique = list(dict.fromkeys(sets))
    index = {s: i for i, s in enumerate(unique)}
    S = len(unique)
    cells = [_set_cells(s) for s in unique]
    K = max(len(c[0]) for c in cells)
    rule_ll = np.zeros((S, N_RULES))
    n_ex = np.zeros((S, 1))
    log_count = np.full((S, K), -1e4)
    cell_log_in = np.zeros((S, K))
    cell_n_in = np.zeros((S, K))
    shares = np.zeros((S, K, 100))
    for i, s in enumerate(unique):
        rule_ll[i] = RULE_LOG_LIK[:, [x - 1 for x in s]].sum(axis=1)
        n_ex[i, 0] = len(s)
        c, size_idx, mem, sh = cells[i]
        n = len(c)
        log_count[i, :n] = np.log(c)
        cell_log_in[i, :n] = LOG_IN[size_idx]
        cell_n_in[i, :n] = mem.sum(axis=1)
        shares[i, :n] = sh
    pairs = [(index[s], int(r["target"]) - 1) for s, r in zip(sets, rows)]
    queries = list(dict.fromkeys(pairs))
    q_index = {q: j for j, q in enumerate(queries)}
    q_set = np.array([q[0] for q in queries], dtype="int64")
    q_target = np.array([q[1] for q in queries], dtype="int64")
    cell_ll = cell_n_in * cell_log_in + (n_ex - cell_n_in) * LOG_OUT
    return {
        "set_rule_log_lik": rule_ll,
        "set_cell_log_lik": cell_ll,
        "cell_log_count": log_count,
        "query_set": q_set,
        "query_rule_member": RULE_MEMBERSHIP[:, q_target].T,
        "query_cell_in_concept": shares[q_set, :, q_target],
        "row_query": np.array([q_index[p] for p in pairs], dtype="int64"),
        "rating": np.array([int(float(r["rating"])) for r in rows], dtype="int64"),
    }


with pm.Model() as model:
    set_rule_log_lik = pm.Data("set_rule_log_lik", np.zeros((1, N_RULES)))
    set_cell_log_lik = pm.Data("set_cell_log_lik", np.zeros((1, 1)))
    cell_log_count = pm.Data("cell_log_count", np.zeros((1, 1)))
    query_set = pm.Data("query_set", np.zeros(1, dtype="int64"))
    query_rule_member = pm.Data("query_rule_member", np.zeros((1, N_RULES)))
    query_cell_in_concept = pm.Data("query_cell_in_concept", np.zeros((1, 1)))
    row_query = pm.Data("row_query", np.zeros(1, dtype="int64"))
    rating = pm.Data("rating", np.zeros(1, dtype="int64"))

    p_mix = pm.Beta("p_mix", 4, 4)
    # Share of rule prior per family: progressions, powers, special sets, contained digit.
    family_w = pm.Dirichlet("family_w", a=np.full(4, 2.0))
    # Progression prior: g^-alpha, bonus for pure multiples and for step 10.
    alpha = pm.HalfNormal("alpha", sigma=2.0)
    bonus_mult = pm.Normal("bonus_mult", mu=0.0, sigma=2.0)
    bonus_ten = pm.Normal("bonus_ten", mu=0.0, sigma=2.0)
    gamma = pm.LogNormal("gamma", mu=0.0, sigma=0.5)

    res_logit = -alpha * np.log(RES_G) + bonus_mult * RES_R0 + bonus_ten * RES_G10
    res_logp = res_logit - pt.logsumexp(res_logit)
    log_fam = pt.log(family_w)
    rule_log_prior = pt.concatenate([log_fam[0] + res_logp, log_fam[OTHER_FAM] + OTHER_LOGU])

    log_rules = pt.log(p_mix) + rule_log_prior[None, :] + gamma * set_rule_log_lik
    log_cells = pt.log1p(-p_mix) - np.log(N_INTERVALS) + cell_log_count + gamma * set_cell_log_lik
    shift = pt.maximum(log_rules.max(axis=1), log_cells.max(axis=1))[:, None]
    u_rules = pt.exp(log_rules - shift)
    u_cells = pt.exp(log_cells - shift)
    z = u_rules.sum(axis=1) + u_cells.sum(axis=1)
    in_concept = (
        (u_rules[query_set] * query_rule_member).sum(axis=1)
        + (u_cells[query_set] * query_cell_in_concept).sum(axis=1)
    ) / z[query_set]

    lapse = pm.Beta("lapse", 2.0, 4.0)
    guess_bias = pm.Beta("guess_bias", 2.0, 2.0)
    p_concept = (1 - lapse) * in_concept[row_query] + lapse * guess_bias
    p_yes = pm.Deterministic("p_yes", pt.clip(p_concept, 1e-6, 1 - 1e-6))
    pm.Bernoulli("response", p=p_yes, observed=rating)
