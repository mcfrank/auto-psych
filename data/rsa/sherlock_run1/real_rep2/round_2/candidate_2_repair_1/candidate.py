"""Sample-based listener: approximate inference via posterior decision precision.

Human listeners choose referents through sample-based decision precision rather
than exact posterior probability matching. Instead of selecting objects in
strict linear proportion to their posterior beliefs, a resource-limited listener
takes multiple samples from their pragmatic posterior, producing a
soft-maximization choice rule with precision beta that sharpens decisions toward
the most probable referent while accounting for speaker-side communicative noise.
"""

import jax
import jax.numpy as jnp
import numpyro.distributions as dist
from memo import memo

from src.rsa.memo_kit import EPS, at, softmax_prior, vec, with_lapse

PARAMS = {
    "alpha": dist.LogNormal(0.0, 1.0),
    "beta": dist.LogNormal(0.0, 1.0),
    "w_features": dist.Normal(0.0, 1.0),
    "w_familiar": dist.Normal(0.0, 2.0),
    "lapse": dist.Beta(1.0, 9.0),
}


@memo
def L0[u: UTT, r: OBJ](lex: ..., prior: ...):
    listener: knows(u)
    listener: chooses(r in OBJ, wpp=vec(prior, r) * at(lex, u, r))
    return Pr[listener.r == r]


@memo
def L1[u: UTT, r: OBJ](alpha, beta, lex: ..., prior: ...):
    listener: thinks[
        speaker: given(r in OBJ, wpp=vec(prior, r)),
        speaker: chooses(
            u in UTT,
            wpp=at(lex, u, r) * exp(alpha * log(L0[u, r](lex, prior) + {EPS})),
        ),
    ]
    listener: observes [speaker.u] is u
    listener: chooses(r in OBJ, wpp=exp(beta * log(Pr[speaker.r == r] + {EPS})))
    return Pr[listener.r == r]


def choice_probs(params, ctx):
    prior = softmax_prior(
        params["w_features"] * ctx.feature_count + params["w_familiar"] * ctx.familiarization
    )
    heard = L1(params["alpha"], params["beta"], ctx.lex, prior)[ctx.utterance]
    prior_choice = jax.nn.softmax(jnp.log(prior + EPS) * params["beta"])
    return with_lapse(jnp.where(ctx.is_prior > 0, prior_choice, heard), params["lapse"])
