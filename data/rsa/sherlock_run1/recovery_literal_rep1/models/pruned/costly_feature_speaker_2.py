"""RSA pragmatic listener (depth 1) reasoning about a cost-sensitive speaker.

Speakers incur an utterance cost proportional to the number of objects sharing
that feature in the visual context, reflecting a communicative penalty for
producing non-distinctive words beyond literal listener informativeness. The
pragmatic listener inverts this speaker, taking utterance costs into account
when evaluating alternatives.
"""

import jax.numpy as jnp
import numpyro.distributions as dist
from memo import memo

from src.rsa.memo_kit import EPS, at, vec, with_lapse

PARAMS = {
    "alpha": dist.LogNormal(0.0, 1.0),
    "cost": dist.Normal(0.0, 1.0),
    "lapse": dist.Beta(1.0, 9.0),
}


@memo
def L0[u: UTT, r: OBJ](lex: ...):
    listener: knows(u)
    listener: chooses(r in OBJ, wpp=at(lex, u, r))
    return Pr[listener.r == r]


@memo
def L1[u: UTT, r: OBJ](alpha, lex: ..., costs: ...):
    listener: thinks[
        speaker: given(r in OBJ, wpp=1),
        speaker: chooses(
            u in UTT,
            wpp=at(lex, u, r) * exp(alpha * log(L0[u, r](lex) + {EPS}) - vec(costs, u)),
        ),
    ]
    listener: observes [speaker.u] is u
    listener: chooses(r in OBJ, wpp=Pr[speaker.r == r])
    return Pr[listener.r == r]


def choice_probs(params, ctx):
    ext = jnp.sum(ctx.lex * (1.0 - ctx.is_sink[:, None]), axis=-1)
    costs = params["cost"] * (ext - 1.0) * (1.0 - ctx.is_sink)
    heard = L1(params["alpha"], ctx.lex, costs)[ctx.utterance]
    uniform = jnp.full_like(heard, 1.0 / heard.shape[0])
    return with_lapse(jnp.where(ctx.is_prior > 0, uniform, heard), params["lapse"])
