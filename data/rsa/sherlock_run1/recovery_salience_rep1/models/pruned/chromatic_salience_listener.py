"""Pragmatic listener with chromatic pop-out and feature simplicity salience.

Listeners evaluate referents through a perceptual salience prior governed by visual
feature complexity and chromatic contrast: simpler objects serve as default prototypes
in neutral displays, while an object rendered in color against grayscale distractors
produces chromatic pop-out that captures attention.
"""

import jax.numpy as jnp
import numpyro.distributions as dist
from memo import memo

from src.rsa.memo_kit import EPS, at, vec, with_lapse, softmax_prior

PARAMS = {
    "alpha": dist.LogNormal(0.0, 1.0),
    "salience": dist.Normal(0.0, 1.0),
    "chromatic_salience": dist.Normal(0.0, 1.0),
    "lapse": dist.Beta(1.0, 9.0),
}


@memo
def L0[u: UTT, r: OBJ](lex: ...):
    listener: knows(u)
    listener: chooses(r in OBJ, wpp=at(lex, u, r))
    return Pr[listener.r == r]


@memo
def L1[u: UTT, r: OBJ](alpha, lex: ..., prior: ...):
    listener: thinks[
        speaker: given(r in OBJ, wpp=vec(prior, r)),
        speaker: chooses(u in UTT, wpp=at(lex, u, r) * exp(alpha * log(L0[u, r](lex) + {EPS}))),
    ]
    listener: observes [speaker.u] is u
    listener: chooses(r in OBJ, wpp=Pr[speaker.r == r])
    return Pr[listener.r == r]


def choice_probs(params, ctx):
    chromatic_contrast = jnp.mean(ctx.grayscale) - ctx.grayscale
    prior = softmax_prior(
        params["salience"] * ctx.feature_count
        + params["chromatic_salience"] * chromatic_contrast
    )
    heard = L1(params["alpha"], ctx.lex, prior)[ctx.utterance]
    return with_lapse(jnp.where(ctx.is_prior > 0, prior, heard), params["lapse"])
