"""Pragmatic listener with a contextual feature-distinctiveness prior.

Listeners maintain an object prior grounded in contextual distinctiveness:
rather than counting features in isolation, an object's visual salience is
determined by the rarity of its features across the visual scene (inverse
feature frequency). Features shared across many objects form redundant background,
whereas rare or unique features produce visual pop-out.
"""

import jax.numpy as jnp
import numpyro.distributions as dist
from memo import memo

from src.rsa.memo_kit import EPS, at, vec, with_lapse, softmax_prior

PARAMS = {
    "alpha": dist.LogNormal(0.0, 1.0),
    "distinctiveness": dist.Normal(0.0, 1.0),
    "lapse": dist.Beta(1.0, 9.0),
}


@memo
def L0[u: UTT, r: OBJ](lex: ...):
    listener: knows(u)
    listener: chooses(r in OBJ, wpp=at(lex, u, r))
    return Pr[listener.r == r]


@memo
def L1[u: UTT, r: OBJ](alpha, lex: ..., prior: ...):
    listener: thinks[
        speaker: given(r in OBJ, wpp=vec(prior, r)),
        speaker: chooses(u in UTT, wpp=at(lex, u, r) * exp(alpha * log(L0[u, r](lex) + {EPS}))),
    ]
    listener: observes [speaker.u] is u
    listener: chooses(r in OBJ, wpp=Pr[speaker.r == r])
    return Pr[listener.r == r]


def choice_probs(params, ctx):
    real_lex = ctx.lex * (1.0 - ctx.is_sink[:, None])
    feat_freq = real_lex.sum(axis=1)
    safe_freq = jnp.where(feat_freq > 0.0, feat_freq, 1.0)
    distinctiveness = (real_lex * (1.0 / safe_freq[:, None])).sum(axis=0)

    prior = softmax_prior(params["distinctiveness"] * distinctiveness)
    heard = L1(params["alpha"], ctx.lex, prior)[ctx.utterance]
    return with_lapse(jnp.where(ctx.is_prior > 0, prior, heard), params["lapse"])
