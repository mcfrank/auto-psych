"""Pragmatic listener reasoning about an entropy-penalized speaker.

Speakers in reference games actively seek communicative clarity: when selecting
a referring expression for an intended referent, they penalize utterances that
leave the pragmatic listener in a state of high referential uncertainty (Shannon
entropy of the listener's posterior beliefs). Pragmatic listeners invert this
ambiguity-averse speaker, expecting referring expressions to target referents
for which the utterance minimizes communicative entropy.
"""

import jax.numpy as jnp
import numpyro.distributions as dist
from memo import memo

from src.rsa.memo_kit import EPS, at, vec, with_lapse

PARAMS = {
    "alpha": dist.LogNormal(0.0, 1.0),
    "w_entropy": dist.Normal(0.0, 1.0),
    "lapse": dist.Beta(1.0, 9.0),
}


@memo
def L0[u: UTT, r: OBJ](lex: ...):
    listener: knows(u)
    listener: chooses(r in OBJ, wpp=at(lex, u, r))
    return Pr[listener.r == r]


@memo
def L1[u: UTT, r: OBJ](alpha, lex: ...):
    listener: thinks[
        speaker: given(r in OBJ, wpp=1),
        speaker: chooses(u in UTT, wpp=at(lex, u, r) * exp(alpha * log(L0[u, r](lex) + {EPS}))),
    ]
    listener: observes [speaker.u] is u
    listener: chooses(r in OBJ, wpp=Pr[speaker.r == r])
    return Pr[listener.r == r]


@memo
def L2[u: UTT, r: OBJ](alpha, w_entropy, lex: ..., entropy: ...):
    listener: thinks[
        speaker: given(r in OBJ, wpp=1),
        speaker: chooses(
            u in UTT,
            wpp=at(lex, u, r)
            * exp(
                alpha * log(L1[u, r](alpha, lex) + {EPS})
                - w_entropy * vec(entropy, u)
            ),
        ),
    ]
    listener: observes [speaker.u] is u
    listener: chooses(r in OBJ, wpp=Pr[speaker.r == r])
    return Pr[listener.r == r]


def choice_probs(params, ctx):
    l1_probs = L1(params["alpha"], ctx.lex)
    entropy = -jnp.sum(l1_probs * jnp.log(l1_probs + EPS), axis=1)
    heard = L2(params["alpha"], params["w_entropy"], ctx.lex, entropy)[ctx.utterance]
    uniform = jnp.full_like(heard, 1.0 / heard.shape[0])
    return with_lapse(jnp.where(ctx.is_prior > 0, uniform, heard), params["lapse"])
