"""RSA pragmatic listener (depth 1) with communicative referability prior.

Listeners model the speaker as choosing an intended referent based on communicative
referability: objects with uniquely distinguishing features have higher prior
probability of being selected as the communicative topic, because a speaker
constrained to a single word can communicate them unambiguously.
"""

import jax.numpy as jnp
import numpyro.distributions as dist
from memo import memo

from src.rsa.memo_kit import EPS, at, softmax_prior, vec, with_lapse

PARAMS = {
    "alpha": dist.LogNormal(0.0, 1.0),
    "w_referable": dist.Normal(0.0, 1.0),
    "w_familiar": dist.Normal(0.0, 2.0),
    "lapse": dist.Beta(1.0, 9.0),
}


@memo
def L0[u: UTT, r: OBJ](lex: ...):
    listener: knows(u)
    listener: chooses(r in OBJ, wpp=at(lex, u, r))
    return Pr[listener.r == r]


@memo
def L1[u: UTT, r: OBJ](alpha, lex: ..., prior: ...):
    listener: thinks[
        speaker: given(r in OBJ, wpp=vec(prior, r)),
        speaker: chooses(u in UTT, wpp=at(lex, u, r) * exp(alpha * log(L0[u, r](lex) + {EPS}))),
    ]
    listener: observes [speaker.u] is u
    listener: chooses(r in OBJ, wpp=Pr[speaker.r == r])
    return Pr[listener.r == r]


def choice_probs(params, ctx):
    mask = 1.0 - ctx.is_sink
    ext = jnp.sum(ctx.lex * mask[:, None], axis=1)
    acc = (ctx.lex * mask[:, None]) / jnp.maximum(1.0, ext[:, None])
    referability = jnp.max(acc, axis=0)
    prior = softmax_prior(
        params["w_referable"] * referability + params["w_familiar"] * ctx.familiarization
    )
    heard = L1(params["alpha"], ctx.lex, prior)[ctx.utterance]
    return with_lapse(jnp.where(ctx.is_prior > 0, prior, heard), params["lapse"])
