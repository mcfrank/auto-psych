"""RSA pragmatic listener with a contextual feature contrast salience prior.

Listeners expect speakers to refer to the most distinctive object in a scene,
weighting referents by their contextual feature contrast (average dissimilarity
to all other objects in the display). This contrast prior is shared as common
knowledge between the listener and the simulated speaker, guiding both prior
choices and pragmatic disambiguation of informative utterances.
"""

import jax.numpy as jnp
import numpyro.distributions as dist
from memo import memo

from src.rsa.memo_kit import EPS, at, softmax_prior, vec, with_lapse

PARAMS = {
    "alpha": dist.LogNormal(0.0, 1.0),
    "w_contrast": dist.Normal(0.0, 1.0),
    "lapse": dist.Beta(1.0, 9.0),
}


@memo
def L0[u: UTT, r: OBJ](lex: ..., prior: ...):
    listener: knows(u)
    listener: chooses(r in OBJ, wpp=vec(prior, r) * at(lex, u, r))
    return Pr[listener.r == r]


@memo
def L1[u: UTT, r: OBJ](alpha, lex: ..., prior: ...):
    listener: thinks[
        speaker: given(r in OBJ, wpp=vec(prior, r)),
        speaker: chooses(
            u in UTT,
            wpp=at(lex, u, r) * exp(alpha * log(L0[u, r](lex, prior) + {EPS})),
        ),
    ]
    listener: observes [speaker.u] is u
    listener: chooses(r in OBJ, wpp=Pr[speaker.r == r])
    return Pr[listener.r == r]


def choice_probs(params, ctx):
    real_lex = ctx.lex * (1.0 - ctx.is_sink)[:, None]
    diff = jnp.abs(real_lex[:, :, None] - real_lex[:, None, :])
    contrast = diff.sum(axis=0).sum(axis=1) / jnp.maximum(real_lex.shape[1] - 1, 1)
    prior = softmax_prior(params["w_contrast"] * contrast)
    heard = L1(params["alpha"], ctx.lex, prior)[ctx.utterance]
    return with_lapse(jnp.where(ctx.is_prior > 0, prior, heard), params["lapse"])
