"""Literal-pragmatic listener population mixture.

Listeners in the population differ in reasoning depth, forming a mixture of
literal listeners (depth 0) and pragmatic listeners (depth 2). Literal listeners
select referents uniformly among all objects consistent with the literal
semantics of the heard word. Pragmatic listeners invert a communicative speaker
who evaluates referring expressions by how informatively they communicate to a
depth-1 pragmatic listener. Observed choices reflect a mixture proportion
between literal and pragmatic comprehenders, separating genuine literal
comprehension from random motor lapses.
"""

import jax.numpy as jnp
import numpyro.distributions as dist
from memo import memo

from src.rsa.memo_kit import EPS, at, with_lapse

PARAMS = {
    "alpha": dist.LogNormal(0.0, 1.0),
    "mix_literal": dist.Beta(1.0, 1.0),
    "lapse": dist.Beta(1.0, 9.0),
}


@memo
def L0[u: UTT, r: OBJ](lex: ...):
    listener: knows(u)
    listener: chooses(r in OBJ, wpp=at(lex, u, r))
    return Pr[listener.r == r]


@memo
def L1[u: UTT, r: OBJ](alpha, lex: ...):
    listener: thinks[
        speaker: given(r in OBJ, wpp=1),
        speaker: chooses(u in UTT, wpp=at(lex, u, r) * exp(alpha * log(L0[u, r](lex) + {EPS}))),
    ]
    listener: observes [speaker.u] is u
    listener: chooses(r in OBJ, wpp=Pr[speaker.r == r])
    return Pr[listener.r == r]


@memo
def L2[u: UTT, r: OBJ](alpha, lex: ...):
    listener: thinks[
        speaker: given(r in OBJ, wpp=1),
        speaker: chooses(u in UTT, wpp=at(lex, u, r) * exp(alpha * log(L1[u, r](alpha, lex) + {EPS}))),
    ]
    listener: observes [speaker.u] is u
    listener: chooses(r in OBJ, wpp=Pr[speaker.r == r])
    return Pr[listener.r == r]


def choice_probs(params, ctx):
    l0 = L0(ctx.lex)[ctx.utterance]
    l2 = L2(params["alpha"], ctx.lex)[ctx.utterance]
    heard = params["mix_literal"] * l0 + (1.0 - params["mix_literal"]) * l2
    uniform = jnp.full_like(heard, 1.0 / heard.shape[0])
    return with_lapse(jnp.where(ctx.is_prior > 0, uniform, heard), params["lapse"])
