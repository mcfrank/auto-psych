"""Pragmatic listener reasoning about a speaker biased by contextual feature prevalence.

Speakers in reference games exhibit a lexical accessibility bias: features shared across
more objects in the visual context are retrieved and produced more readily than rare,
context-specific features. Pragmatic listeners reason at depth 2, inverting this
prevalence-biased speaker and correctly expecting that speakers will frequently produce
prevalent labels even when describing objects that possess more specific distinguishing
features. On trials with no informative word, choices are uniform. A lapse parameter
mixes in uniform guessing.
"""

import jax.numpy as jnp
import numpyro.distributions as dist
from memo import memo

from src.rsa.memo_kit import EPS, at, vec, with_lapse

PARAMS = {
    "alpha": dist.LogNormal(0.0, 1.0),
    "beta": dist.Normal(0.0, 1.0),
    "lapse": dist.Beta(1.0, 9.0),
}


@memo
def L0[u: UTT, r: OBJ](lex: ...):
    listener: knows(u)
    listener: chooses(r in OBJ, wpp=at(lex, u, r))
    return Pr[listener.r == r]


@memo
def L1[u: UTT, r: OBJ](alpha, lex: ..., accessibility: ...):
    listener: thinks[
        speaker: given(r in OBJ, wpp=1),
        speaker: chooses(
            u in UTT,
            wpp=at(lex, u, r)
            * vec(accessibility, u)
            * exp(alpha * log(L0[u, r](lex) + {EPS})),
        ),
    ]
    listener: observes [speaker.u] is u
    listener: chooses(r in OBJ, wpp=Pr[speaker.r == r])
    return Pr[listener.r == r]


@memo
def L2[u: UTT, r: OBJ](alpha, lex: ..., accessibility: ...):
    listener: thinks[
        speaker: given(r in OBJ, wpp=1),
        speaker: chooses(
            u in UTT,
            wpp=at(lex, u, r)
            * vec(accessibility, u)
            * exp(alpha * log(L1[u, r](alpha, lex, accessibility) + {EPS})),
        ),
    ]
    listener: observes [speaker.u] is u
    listener: chooses(r in OBJ, wpp=Pr[speaker.r == r])
    return Pr[listener.r == r]


def choice_probs(params, ctx):
    real_lex = ctx.lex * (1.0 - ctx.is_sink[:, None])
    freq = jnp.sum(real_lex, axis=1)
    accessibility = jnp.where(
        ctx.is_sink > 0, 1.0, jnp.exp(params["beta"] * jnp.log(jnp.maximum(freq, 1.0)))
    )

    heard = L2(params["alpha"], ctx.lex, accessibility)[ctx.utterance]
    uniform = jnp.full_like(heard, 1.0 / heard.shape[0])
    return with_lapse(
        jnp.where(ctx.is_prior > 0, uniform, heard), params["lapse"]
    )
